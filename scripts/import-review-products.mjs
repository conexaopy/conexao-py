  const skus = products.map((p) => p.sku);
  const { data: existing, error: existingError } = await supabase
    .from("products")
    .select("sku")
    .in("sku", skus);

  if (existingError) {
    console.error("Erro ao verificar registros existentes:", existingError);
    process.exit(1);
  }

  const existingSkus = new Set((existing ?? []).map((p) => p.sku));
  const pending = products.filter((p) => !existingSkus.has(p.sku));

  console.log(`Já existentes: ${existingSkus.size}`);
  console.log(`Novos para inserir: ${pending.length}`);

  if (pending.length === 0) {
    console.log("Nada para inserir.");
    return;
  }

  const batchSize = 25;
  let inserted = 0;

  for (let i = 0; i < pending.length; i += batchSize) {
    const batch = pending.slice(i, i + batchSize);

    const { error } = await supabase
      .from("products")
      .insert(batch);

    if (error) {
      console.error(`Erro no lote iniciado em ${i + 1}:`, error);
      process.exit(1);
    }

    inserted += batch.length;
    console.log(`Inseridos: ${inserted}/${pending.length}`);
  }

  console.log("IMPORTAÇÃO DE REVISÃO CONCLUÍDA.");
  console.log("Todos os registros foram criados como active=false e stock_quantity=0.");
